test_that("dataset_setup builds the dataset tree next to Projects", {
    local_tm_settings()
    root <- local_root()
    utils::capture.output(
        d <- dataset_setup("GEO_GSE1", root = root, confirm = FALSE,
                           auto_cleanup = FALSE, assign_global = FALSE)
    )
    expect_equal(d$bd, file.path(root, "heiBOX", "Datasets", "public", "GEO_GSE1"))
    expect_setequal(names(d), c("bd", "dir_home", "dir_raw", "dir_processed", "dir_scripts", "datasets"))
    expect_true(file.exists(file.path(d$bd, "README.md")))
    marker <- read.dcf(file.path(d$bd, ".toastmaker"))
    expect_equal(unname(marker[1, c("Type", "Source")]), c("dataset", "public"))

    utils::capture.output(
        i <- dataset_setup("2026-03-12_cohortA", source = "internal", root = root,
                           confirm = FALSE, auto_cleanup = FALSE, assign_global = FALSE)
    )
    expect_equal(dirname(i$bd), file.path(root, "heiBOX", "Datasets", "internal"))
    expect_true(any(grepl("Generated by", readLines(file.path(i$bd, "README.md")))))

    expect_error(setup_quiet("x", type = "dataset", root = root), "'type' must be one of")
})

test_that("projects link to datasets in both directions", {
    local_tm_settings()
    root <- local_root()
    utils::capture.output(
        d <- dataset_setup("GEO_GSE1", root = root, confirm = FALSE,
                           auto_cleanup = FALSE, assign_global = FALSE)
    )
    p <- setup_quiet("KO", datasets = "GEO_GSE1", root = root)
    expect_equal(p$datasets$public$GEO_GSE1, d$bd)
    expect_false("datasets" %in% names(.tm_dirs(p)))

    pm <- read.dcf(file.path(p$bd, ".toastmaker"))
    expect_equal(unname(pm[1, "Datasets"]), "public/GEO_GSE1")
    dm <- read.dcf(file.path(d$bd, ".toastmaker"))
    expect_equal(unname(dm[1, "UsedBy"]), "Projects/KO")

    # a second project is appended; repeating does not duplicate
    setup_quiet("KO2", datasets = "public/GEO_GSE1", root = root)
    setup_quiet("KO2", datasets = "GEO_GSE1", root = root)
    dm <- read.dcf(file.path(d$bd, ".toastmaker"))
    expect_equal(unname(dm[1, "UsedBy"]), "Projects/KO, Projects/KO2")

    expect_error(setup_quiet("KO", datasets = "nope", root = root), "not found")
})

test_that("ambiguous dataset names must say public/ or internal/", {
    local_tm_settings()
    root <- local_root()
    for (s in c("public", "internal")) {
        utils::capture.output(dataset_setup("X", source = s, root = root, confirm = FALSE,
                                            auto_cleanup = FALSE, assign_global = FALSE))
    }
    expect_error(setup_quiet("KO", datasets = "X", root = root), "exists in both")
    p <- setup_quiet("KO", datasets = "internal/X", root = root)
    expect_match(p$datasets$internal$X, "internal/X$")
})

